function fill(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`))
}

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  return fill((dicts[lang] ?? en)[key] ?? en[key], vars)
}

/** Non-React access (engine, helpers) */
export function t(key: TKey, vars?: Record<string, string | number>): string {
  return translate(useSettings.getState().language, key, vars)
}

export function useT(): (key: TKey, vars?: Record<string, string | number>) => string {
  const lang = useSettings((s) => s.language)
  return useCallback((key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang])
}

export function locale(): string {
  return useSettings.getState().language === 'de' ? 'de-DE' : 'en-US'
}
